export { ROWS as FONT_5X7 };
export function cleanMessage(message = 'SEND IT!') {
  return String(message).toUpperCase().replace(/[^A-Z0-9 !?.-]/g,' ').slice(0,40).trim() || 'SEND IT!';
}
export const textDuration = (message, columns = 17) => (columns + cleanMessage(message).length * 6) / 4;
export function letterPixel(message, point, time) {
  if (point.textX === -1 || point.textY === -1) return null;
  message = cleanMessage(message);
  const columns = point.textWidth || 17, rows = point.textHeight || 19;
  const x = point.textX ?? Math.round((point.x + 0.88) / 1.76 * 16);
  const y = point.textY ?? Math.round((0.92 - point.y) / 1.84 * 18);
  const scroll = Math.floor(time * 4) - columns;
  const px = x + scroll, py = y - Math.floor((rows - 7) / 2);
  if (px < 0 || py < 0 || py >= 7) return null;
  const character = Math.floor(px / 6), col = px % 6;
  if (character >= message.length || col === 5) return null;
  return ROWS[message[character]][py][col] === '1' ? { character, row: py, col } : null;
}
